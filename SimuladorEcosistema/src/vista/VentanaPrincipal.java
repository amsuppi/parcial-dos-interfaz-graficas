    /** Conecta la ventana y sus pantallas con el controlador. */
    public void setControlador(SimulacionController controlador) {
        this.controlador = controlador;
        panelConfiguracion.setControlador(controlador);
        panelSimulacion.setControlador(controlador);
        panelReporte.setControlador(controlador);
    }

    // ---- Navegación entre pantallas ----

    public void mostrarPantallaConfiguracion() {
        mostrarTarjeta("configuracion");
    }

    public void mostrarPantallaSimulacion() {
        mostrarTarjeta("simulacion");
    }

    public void mostrarPantallaReporte() {
        mostrarTarjeta("reporte");
    }

    private void mostrarTarjeta(String nombre) {
        ((CardLayout) getContentPane().getLayout()).show(getContentPane(), nombre);
    }

    // ---- Mensajes ----

    /** Mensaje de estado en la barra inferior de las pantallas. */
    public void mostrarEstadoApp(String mensaje) {
        panelConfiguracion.mostrarEstado(mensaje);
        panelSimulacion.mostrarEstado(mensaje);
    }

    public void mostrarError(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Atención", JOptionPane.WARNING_MESSAGE);
    }

    /** Habilita las opciones para ver el reporte (cuando la simulación terminó). */
    public void habilitarReporte(boolean habilitado) {
        panelSimulacion.habilitarReporte(habilitado);
        mniVerReporte.setEnabled(habilitado);
    }

    /** Confirmación antes de descartar una simulación en curso (pantalla 05 del Figma). */
    public boolean confirmarNuevaSimulacion() {
        Object[] opciones = {"Sí, empezar nueva", "Cancelar"};
        int respuesta = JOptionPane.showOptionDialog(this,
                "Se va a descartar la simulación actual y no se puede recuperar.",
                "¿Empezar una nueva simulación?", JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[1]);
        return respuesta == 0;
    }

